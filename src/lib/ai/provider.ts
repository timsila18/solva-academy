import { getEnv } from "@/lib/config/env";

export type AiGenerateInput = {
  system: string;
  prompt: string;
  context?: string[];
  responseFormat?: "text" | "json";
};

export type AiGenerateResult = {
  content: string;
  structured?: Record<string, unknown>;
  inputTokens: number;
  outputTokens: number;
  latencyMs: number;
};

export type AiModerationResult = {
  decision: "allow" | "flag" | "block" | "review";
  riskLevel: "low" | "normal" | "high" | "critical";
  categories: string[];
  notes?: string;
};

export interface AiProvider {
  provider: string;
  modelSlug: string;
  generate(input: AiGenerateInput): Promise<AiGenerateResult>;
  moderate(text: string): Promise<AiModerationResult>;
  embed(text: string): Promise<number[]>;
}

export function estimateTokens(text: string) {
  return Math.max(1, Math.ceil(text.trim().length / 4));
}

function deterministicVector(text: string, dimensions = 16) {
  const vector = Array.from({ length: dimensions }, () => 0);
  for (let index = 0; index < text.length; index += 1) {
    vector[index % dimensions] += text.charCodeAt(index) / 255;
  }
  const magnitude = Math.sqrt(vector.reduce((sum, value) => sum + value * value, 0)) || 1;
  return vector.map((value) => Number((value / magnitude).toFixed(6)));
}

export class MockAiProvider implements AiProvider {
  provider = "mock";
  modelSlug = "solco-mock-v1";

  async generate(input: AiGenerateInput): Promise<AiGenerateResult> {
    const start = Date.now();
    const contextLines = input.context?.length ? `\n\nAuthorized context used:\n${input.context.map((item, index) => `${index + 1}. ${item.slice(0, 240)}`).join("\n")}` : "";
    const content = [
      "Draft generated by Solco Intelligence mock provider.",
      "",
      "Suggested response:",
      input.prompt.length > 700 ? `${input.prompt.slice(0, 700)}...` : input.prompt,
      contextLines,
      "",
      "Human review is required before this is used for teaching, assessment, compliance, certificates, or child learning.",
    ].join("\n");

    return {
      content,
      structured: input.responseFormat === "json" ? { draft: content, requiresReview: true, provider: this.provider } : undefined,
      inputTokens: estimateTokens(`${input.system}\n${input.prompt}\n${input.context?.join("\n") ?? ""}`),
      outputTokens: estimateTokens(content),
      latencyMs: Date.now() - start,
    };
  }

  async moderate(text: string): Promise<AiModerationResult> {
    const lower = text.toLowerCase();
    const blockedPatterns = ["ignore previous instructions", "reveal system prompt", "bypass safety", "delete all", "leak private"];
    const highRiskPatterns = ["self-harm", "child abuse", "password", "bank account", "national id"];
    const blocked = blockedPatterns.filter((pattern) => lower.includes(pattern));
    const risky = highRiskPatterns.filter((pattern) => lower.includes(pattern));
    if (blocked.length) return { decision: "block", riskLevel: "high", categories: blocked, notes: "Prompt-injection or unsafe control attempt detected." };
    if (risky.length) return { decision: "review", riskLevel: "high", categories: risky, notes: "Sensitive topic requires human review." };
    return { decision: "allow", riskLevel: "low", categories: [] };
  }

  async embed(text: string): Promise<number[]> {
    return deterministicVector(text);
  }
}

export function getAiProvider(): AiProvider {
  const env = getEnv();
  if (env.AI_PROVIDER !== "mock") {
    return new MockAiProvider();
  }
  return new MockAiProvider();
}
